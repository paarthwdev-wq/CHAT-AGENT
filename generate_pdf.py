def has_devanagari(text: str) -> bool:
    """Checks if text contains Devanagari (Hindi) script codepoints."""
    return any(0x0900 <= ord(c) <= 0x097F for c in text)

def clean_text_for_font(text: str, is_bold: bool = False) -> tuple:
    """
    Cleans typographic marks, selects appropriate font (Hindi or English),
    and safely returns cleaned text and fontName.
    """
    if not text:
        return "", FONT_REGULAR

    # Common typographical normalizations
    normalized = (text.replace('–', '-')
                      .replace('—', ' - ')
                      .replace('’', "'")
                      .replace('‘', "'")
                      .replace('“', '"')
                      .replace('”', '"')
                      .replace('…', '...')
                      .replace('\u2022', '•'))

    # If Hindi text is present and Nirmala is registered, use it
    if HAS_HINDI_FONT and has_devanagari(normalized):
        selected_font = FONT_HINDI_BOLD if is_bold else FONT_HINDI_REG
        return normalized, selected_font

    selected_font = FONT_BOLD if is_bold else FONT_REGULAR

    if selected_font.startswith('Helvetica'):
        # Fallback for base 14 PDF fonts
        return normalized.encode('latin-1', 'replace').decode('latin-1'), selected_font

    return normalized, selected_font

def format_inline_markdown(text: str, default_font: str = None) -> str:
    """Formats math symbols, bold, italics, and code tags for ReportLab Paragraphs."""
    cleaned = (text.replace('^2', '²')
                   .replace('^3', '³')
                   .replace('^n', 'ⁿ')
                   .replace(r'\times', '×')
                   .replace(r'\div', '÷')
                   .replace(r'\pm', '±')
                   .replace(r'\le', '≤')
                   .replace(r'\ge', '≥')
                   .replace(r'\approx', '≈')
                   .replace(r'\neq', '≠')
                   .replace(r'\infty', '∞')
                   .replace(r'\pi', 'π'))
    cleaned = re.sub(r'\$\$(.*?)\$\$', r'<b>\1</b>', cleaned)
    cleaned = re.sub(r'\$(.*?)\$', r'\1', cleaned)

    # XML Escape
    t = cleaned.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')

    # Bold: **bold**
    t = re.sub(r'\*\*(.*?)\*\*', r'<b>\1</b>', t)
    # Italic: *italic*
    t = re.sub(r'(?<!\*)\*(?!\*)(.*?)\*', r'<i>\1</i>', t)
    # Inline code: `code`
    t = re.sub(r'`(.*?)`', r'<font face="Courier" color="#0369a1">\1</font>', t)

    return t

def create_pdf(output_path: str, title: str, content: str, subtitle: str = "Official Antigravity Executive Document"):
    """Compiles publication-grade PDF using ReportLab Flowables."""
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)

    # Standard A4: 595.27 x 841.89 pt. Margins: 42 pt. Available width = 511.27 pt
    doc = SimpleDocTemplate(
        output_path,
        pagesize=A4,
        rightMargin=42,
        leftMargin=42,
        topMargin=42,
        bottomMargin=42
    )

    styles = getSampleStyleSheet()

    # --- Typographic Hierarchy (Executive Palette) ---
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName=FONT_HINDI_BOLD if has_devanagari(title) else FONT_BOLD,
        fontSize=21,
        leading=25,
        textColor=colors.HexColor('#0C2340'),
        spaceAfter=5
    )

    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName=FONT_HINDI_REG if has_devanagari(subtitle) else FONT_REGULAR,
        fontSize=10,
        leading=14,
        textColor=colors.HexColor('#1D4ED8'),
        spaceAfter=10
    )

    h1_style = ParagraphStyle(
        'DocH1',
        parent=styles['Heading1'],
        fontName=FONT_BOLD,
        fontSize=14,
        leading=18,
        textColor=colors.HexColor('#0C2340'),
        spaceBefore=14,
        spaceAfter=6,
        keepWithNext=True
    )

    h2_style = ParagraphStyle(
        'DocH2',
        parent=styles['Heading2'],
        fontName=FONT_BOLD,
        fontSize=11.5,
        leading=15,
        textColor=colors.HexColor('#1D4ED8'),
        spaceBefore=10,
        spaceAfter=4,
        keepWithNext=True
    )

    h3_style = ParagraphStyle(
        'DocH3',
        parent=styles['Heading3'],
        fontName=FONT_BOLD,
        fontSize=10,
        leading=13,
        textColor=colors.HexColor('#0284C7'),
        spaceBefore=8,
        spaceAfter=3,
        keepWithNext=True
    )

    body_style = ParagraphStyle(
        'DocBody',
        parent=styles['Normal'],
        fontName=FONT_REGULAR,
        fontSize=9,
        leading=13.5,
        textColor=colors.HexColor('#1E293B'),
        spaceAfter=5
    )

    bullet_style = ParagraphStyle(
        'DocBullet',
        parent=styles['Normal'],
        fontName=FONT_REGULAR,
        fontSize=9,
        leading=13.5,
        textColor=colors.HexColor('#334155'),
        leftIndent=14,
        spaceAfter=3
    )

    callout_style = ParagraphStyle(
        'DocCallout',
        parent=styles['Normal'],
        fontName=FONT_REGULAR,
        fontSize=8.5,
        leading=12.5,
        textColor=colors.HexColor('#0F172A'),
        leftIndent=6,
        spaceBefore=2,
        spaceAfter=2
    )

    story = []

    # 1. Title, Subtitle, and Executive Rule
    safe_title, title_font = clean_text_for_font(title, is_bold=True)
    safe_sub, sub_font = clean_text_for_font(subtitle, is_bold=False)

    title_style.fontName = title_font
    subtitle_style.fontName = sub_font

    story.append(Paragraph(safe_title, title_style))
    story.append(Paragraph(safe_sub, subtitle_style))
    story.append(HRFlowable(width="100%", thickness=2.5, color=colors.HexColor('#0C2340'), spaceAfter=10))

    # 2. Parse Markdown Content Lines
    lines = content.split('\n')
    i = 0
    total_lines = len(lines)
    AVAILABLE_WIDTH = 511.0

    while i < total_lines:
        raw_line = lines[i].strip()
        if not raw_line:
            story.append(Spacer(1, 4))
            i += 1
            continue

        # Markdown Table Detection (| Col 1 | Col 2 | ...)
        if raw_line.startswith('|') and raw_line.endswith('|'):
            table_raw_rows = []
            while i < total_lines and lines[i].strip().startswith('|') and lines[i].strip().endswith('|'):
                cur_row = lines[i].strip()
                # Ignore markdown separator line like |:---|:---|
                if not re.match(r'^\|[\s\-:|]+\|$', cur_row):
                    cols = [c.strip() for c in cur_row.strip('|').split('|')]
                    table_raw_rows.append(cols)
                i += 1

            if table_raw_rows:
                try:
                    num_cols = max(len(r) for r in table_raw_rows)
                    # Normalize rows to same number of columns
                    normalized_rows = []
                    for r in table_raw_rows:
                        if len(r) < num_cols:
                            r = r + [''] * (num_cols - len(r))
                        normalized_rows.append(r[:num_cols])

                    # Calculate max content length for proportional column widths
                    col_max_lens = [max(len(row[c]) for row in normalized_rows) for c in range(num_cols)]
                    total_chars = sum(col_max_lens) or num_cols
                    # Calculate widths with minimum 40pt
                    col_widths = [max(45.0, (col_len / total_chars) * AVAILABLE_WIDTH) for col_len in col_max_lens]
                    scale = AVAILABLE_WIDTH / sum(col_widths)
                    final_widths = [w * scale for w in col_widths]

                    # Wrap cells in Paragraphs
                    formatted_table_data = []
                    for row_idx, r in enumerate(normalized_rows):
                        formatted_row = []
                        is_header = (row_idx == 0)
                        for c in r:
                            safe_c, c_font = clean_text_for_font(c, is_bold=is_header)
                            fmt_text = format_inline_markdown(safe_c)
                            cell_style = ParagraphStyle(
                                f'Cell_{row_idx}',
                                parent=styles['Normal'],
                                fontName=c_font,
                                fontSize=8 if not is_header else 8.5,
                                leading=11 if not is_header else 12,
                                textColor=colors.white if is_header else colors.HexColor('#1E293B'),
                                alignment=1 if is_header else 0
                            )
                            formatted_row.append(Paragraph(fmt_text, cell_style))
                        formatted_table_data.append(formatted_row)

                    t = Table(formatted_table_data, colWidths=final_widths)
                    t.setStyle(TableStyle([
                        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#0C2340')),
                        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
                        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
                        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
                        ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
                        ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#94A3B8')),
                        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#F8FAFC')]),
                        ('TOPPADDING', (0, 0), (-1, -1), 5),
                        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
                        ('LEFTPADDING', (0, 0), (-1, -1), 6),
                        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
                    ]))
                    story.append(t)
                    story.append(Spacer(1, 6))
                except Exception as t_err:
                    print(f"[PDF Tool] Table render fallback: {t_err}", file=sys.stderr)
            continue

        clean_line, line_font = clean_text_for_font(raw_line)

        # Headings
        if clean_line.startswith('# '):
            h_text = format_inline_markdown(clean_line[2:].strip())
            h_style = ParagraphStyle('H1_Active', parent=h1_style, fontName=line_font)
            story.append(Paragraph(h_text, h_style))
            story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#1D4ED8'), spaceAfter=5))
        elif clean_line.startswith('## '):
            h_text = format_inline_markdown(clean_line[3:].strip())
            h_style = ParagraphStyle('H2_Active', parent=h2_style, fontName=line_font)
            story.append(Paragraph(h_text, h_style))
        elif clean_line.startswith('### '):
            h_text = format_inline_markdown(clean_line[4:].strip())
            h_style = ParagraphStyle('H3_Active', parent=h3_style, fontName=line_font)
            story.append(Paragraph(h_text, h_style))
        elif clean_line.startswith('#### '):
            h_text = format_inline_markdown(clean_line[5:].strip())
            story.append(Paragraph(f"<b>{h_text}</b>", body_style))

        # Bullet Points
        elif clean_line.startswith(('- ', '* ', '• ')):
            bullet_text = clean_line[2:].strip()
            fmt_bullet = format_inline_markdown(bullet_text)
            b_style = ParagraphStyle('Bullet_Active', parent=bullet_style, fontName=line_font)
            story.append(Paragraph(f"• {fmt_bullet}", b_style))

        # Numbered Lists (e.g. 1. 2.)
        elif re.match(r'^\d+\.\s', clean_line):
            fmt_num = format_inline_markdown(clean_line)
            b_style = ParagraphStyle('Num_Active', parent=bullet_style, fontName=line_font)
            story.append(Paragraph(fmt_num, b_style))

        # Callout Block: > Note / > Tip / > Warning / > Key Insight
        elif clean_line.startswith('> '):
            callout_text = clean_line[2:].strip()

            # Dynamic categorization of callouts
            border_color = colors.HexColor('#0284C7')  # Default blue
            bg_color = colors.HexColor('#F0F9FF')
            prefix_badge = "💡 <b>KEY INSIGHT &amp; NOTE:</b><br/>"

            lower_c = callout_text.lower()
            if 'warning' in lower_c or 'caution' in lower_c:
                border_color = colors.HexColor('#DC2626')
                bg_color = colors.HexColor('#FEF2F2')
                prefix_badge = "⚠️ <b>CRITICAL WARNING &amp; PREREQUISITE:</b><br/>"
            elif 'tip' in lower_c or 'hack' in lower_c or 'exam' in lower_c:
                border_color = colors.HexColor('#059669')
                bg_color = colors.HexColor('#ECFDF5')
                prefix_badge = "🎯 <b>EXAM HACK &amp; PERFORMANCE TIP:</b><br/>"
            elif 'takeaway' in lower_c or 'summary' in lower_c:
                border_color = colors.HexColor('#4338CA')
                bg_color = colors.HexColor('#EEF2FF')
                prefix_badge = "📌 <b>EXECUTIVE TAKEAWAY:</b><br/>"

            c_p = Paragraph(f"{prefix_badge}{format_inline_markdown(callout_text)}", callout_style)
            try:
                c_table = Table([[c_p]], colWidths=[AVAILABLE_WIDTH])
                c_table.setStyle(TableStyle([
                    ('BACKGROUND', (0, 0), (-1, -1), bg_color),
                    ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
                    ('LINELEFT', (0, 0), (0, -1), 3.5, border_color),
                    ('TOPPADDING', (0, 0), (-1, -1), 6),
                    ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
                    ('LEFTPADDING', (0, 0), (-1, -1), 10),
                    ('RIGHTPADDING', (0, 0), (-1, -1), 10),
                ]))
                story.append(c_table)
                story.append(Spacer(1, 4))
            except Exception:
                story.append(c_p)

        else:
            fmt_body = format_inline_markdown(clean_line)
            b_style = ParagraphStyle('Body_Active', parent=body_style, fontName=line_font)
            story.append(Paragraph(fmt_body, b_style))

        i += 1

    story.append(Spacer(1, 15))
    doc.build(story, canvasmaker=NumberedCanvas)
    return output_path

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate Executive PDF Document")
    parser.add_argument("--out", required=True, help="Output PDF file path")
    parser.add_argument("--title", required=True, help="Title of the PDF")
    parser.add_argument("--content", required=True, help="Text content or path to text file")
    parser.add_argument("--subtitle", default="Antigravity AI Executive Document", help="Subtitle")

    args = parser.parse_args()

    content_text = args.content
    if os.path.isfile(args.content):
        with open(args.content, "r", encoding="utf-8") as f:
            content_text = f.read()

    pdf_file = create_pdf(args.out, args.title, content_text, args.subtitle)
    print(f"SUCCESS: {pdf_file}")
