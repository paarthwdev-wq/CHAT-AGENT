"""
Desktop-Grade Executive PDF Generator Utility for Antigravity AI
Compiles publication-quality, executive master reports, study compendiums, and cheat sheets.
Features:
- A4 Standard page geometry with balanced printable margins
- TrueType Hindi/Devanagari & Unicode symbol support (Nirmala UI / Segoe / DejaVu)
- NumberedCanvas with dynamic 'Page X of Y' and running headers
- Dynamic column-width calculating tables with zebra striping and dark executive headers
- Thematic callout cards (Notes, Exam Hacks, Warnings, Summaries) with colored accent borders
- Mathematical symbol typography (superscripts, operations, greek symbols)
- Non-orphaned headings (keepWithNext=True)
"""

